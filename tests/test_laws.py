"""Распознавание законов (роль 3). Запуск: python -m pytest -q tests/test_laws.py"""
import pytest

from app.pipeline import get_index


def law_ids(text):
    return [m.law_id for m in get_index().find_laws(text)]


@pytest.mark.parametrize("text, expected", [
    # склонения и регистр
    ("ст. 23 Налогового кодекса", [15]),
    ("статьей 5 Гражданского кодекса Российской Федерации", [5]),
    ("ст. 5 Уголовно-процессуального кодекса", [12]),
    ("СОГЛАСНО СТАТЬЕ 25 ЛЕСНОГО КОДЕКСА РОССИЙСКОЙ ФЕДЕРАЦИИ", [14]),
    ("см. ст. 21 тк рф", [10]),
    ("ст. 5 Кодекса об административных правонарушениях", [17]),
    # сокращения, которых нет в базе
    ("ч. 3, ст. 30.1 КоАП", [17]),
    ("ст.19.24 ч.1 КРФоАП", [17]),
    ("ст. 51 ГрК РФ", [4]),
    ("п. 10 АПК", [0]),
    # шум: латиница вместо кириллицы, слипшиеся слова, цифра вместо буквы
    ("ст. 5 НК PФ", [15]),
    ("ст. 5 HK РФ", [15]),
    ("ст.374НК РФ", [15]),
    ("ст. 5 ГКРФ", [5]),
    # опечатки
    ("ст. 5 Налогвого кодекса", [15]),
    ("ст. 5 Трудвого кодекса", [10]),
    ("ст. 5 Граджанского кодекса", [5]),
    ("п. 2 Указа Президена РФ №859", [828]),
    # номер, дата, название — в любом порядке и форме
    ("п. 1 ст. 3 Федерального закона №417-ФЗ от 04.08.2023", [65]),
    ("ст. 5 Федерального закона от 26.10.2002 № 127-ФЗ", [386]),
    ("ст. 5 ФЗ от 23 августа 1996 г. N 127-ФЗ", [488]),
    ("ст. 5 Федерального закона № 127-ФЗ «О науке и государственной научно-технической политике»", [488]),
    ("ст. 5 Закона РФ от 07.02.1992 № 2300-1", [984]),
    ("п. 2 Указа Президента РФ от 17.04.2025 № 240", [543]),
    ("См. п. 1 Распоряжения Президента РФ №34-рп от 05.02.2025.", [21]),
    ("Перечислены пункты 2 и 3 ПБУ 15/2008.", [1047]),
    # неоднозначный номер без подсказок -> самый цитируемый закон
    ("ст. 5 ФЗ №127-ФЗ", [386]),
    ("ст. 5 44-ФЗ", [210]),
    # краткие названия
    ("ст. 5 Закона о банкротстве", [386]),
    ("ст. 44 Закона о связи", [370]),
    ("ст. 5 Закона о защите прав потребителей", [984]),
])
def test_found(text, expected):
    assert law_ids(text) == expected


@pytest.mark.parametrize("text", [
    "ст. 5 рандомного кодекса",
    "ст. 5 ФЗ №20-456",                       # номера нет в базе
    "ст. 9 Федерального закона от 26 января 1996 г. № 15-ФЗ",  # 15-ФЗ в базе, но другой даты
    "ст. 5 Конституции РФ",
    "в связи с этим ст. 5 закона",
    "Заказ №127-ФЗ от 07.06.2025: обозначение",
    "Билет №34-рп, ряд 5",
    "ЖК «Речной», корпус 2",
    "В объявлении написано «АРЕНДА»: помещение",
])
def test_not_found(text):
    assert law_ids(text) == []


def test_ambiguous_number_resolved_by_earlier_mention():
    text = ("Федеральный закон от 23.08.1996 № 127-ФЗ «О науке и государственной "
            "научно-технической политике». Позже в ст. 7 ФЗ №127-ФЗ сказано …")
    assert law_ids(text) == [488, 488]


def test_definition_alias():
    text = ("Федеральный закон от 26.10.2002 № 127-ФЗ (далее — Закон о несостоятельности). "
            "Согласно ст. 5 Закона о несостоятельности …")
    assert law_ids(text) == [386, 386, 386]


def test_spans_point_to_original_text():
    text = "Согласно ст. 5 Федерального закона от 26.10.2002 № 127-ФЗ, суд …"
    (m,) = get_index().find_laws(text)
    assert text[m.start:m.end] == "Федерального закона от 26.10.2002 № 127-ФЗ"
